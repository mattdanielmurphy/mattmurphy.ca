#!/usr/bin/env python3
"""Writes palette.css from ai-os design/candidates/directions.json. Colours are never hand-picked:
every value is a step of a hue in that file. Slub is green-led (Matt, 2026-11-20), so the three palettes are
two single-green ramps and one mix of the green hues across the candidate directions."""
import json, os
src = os.path.expanduser('~/projects/ai-os/design/candidates/directions.json')
D = json.load(open(src))['directions']
hue = lambda fam, name: next(h for h in D[fam]['hues'] if h['name'] == name)
N = D['prairie']['neutral']
# ramp: 8 steps of one hue. --c0 is the outermost band (strongest against the page), --c7 the one next to the ink.
RAMP_L = [10, 9, 7, 6, 5, 4, 3, 2]
RAMP_D = [11, 10, 9, 7, 6, 5, 4, 3]
GREENS = [('synth', 'phosphor'), ('prairie', 'aurora'), ('prairie', 'aspen'), ('apothecary', 'absinthe'),
          ('apothecary', 'verdigris'), ('apothecary', 'camphor'), ('prairie', 'spruce'), ('apothecary', 'uranium glass')]
def cols(pal, mode):
    if pal in ('aurora', 'phosphor'):
        h = hue('prairie', 'aurora') if pal == 'aurora' else hue('synth', 'phosphor')
        ramp = [h[mode][i] for i in (RAMP_L if mode == 'light' else RAMP_D)]
        return ramp + ramp
    hs = [hue(f, n) for f, n in GREENS]
    return [h['light'][8] for h in hs] + [h['light'][10] for h in hs] if mode == 'light' else [h['dark'][9] for h in hs] + [h['dark'][10] for h in hs]
def block(pal, mode):
    n = N[mode]
    rows = [('--bg', N['bgLight'] if mode == 'light' else N['bgDark']), ('--ink', n[11]), ('--soft', n[9]), ('--line', n[4]), ('--chip', n[1])]
    rows += [(f'--c{i}', c) for i, c in enumerate(cols(pal, mode))]
    return f'[data-pal="{pal}"]' + '{' + ';'.join(f'{k}:{v}' for k, v in rows) + '}'
out = ['/* Generated by make-palette.py from ai-os design/candidates/directions.json. Do not edit. */']
out += [block(p, 'light') for p in ('aurora', 'phosphor', 'greens')]
out += ['@media (prefers-color-scheme: dark){'] + [block(p, 'dark') for p in ('aurora', 'phosphor', 'greens')] + ['}']
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'palette.css'), 'w').write('\n'.join(out) + '\n')
print('palette.css written')
