#!/usr/bin/env python3
"""Writes palette.css from ai-os design/candidates/directions.json (never hand-pick colours)."""
import json, os
src = os.path.expanduser('~/projects/ai-os/design/candidates/directions.json')
d = json.load(open(src))['directions']
out = ['/* Generated by make-palette.py from ai-os design/candidates/directions.json. Do not edit. */']
def block(sel, v, mode):
    n = v['neutral']
    if mode == 'light':
        rows = [('--bg', n['bgLight']), ('--ink', n['light'][11]), ('--soft', n['light'][9]), ('--line', n['light'][4]), ('--chip', n['light'][1])]
        cols = [h['light'][8] for h in v['hues']] + [h['light'][10] for h in v['hues']]
    else:
        rows = [('--bg', n['bgDark']), ('--ink', n['dark'][11]), ('--soft', n['dark'][9]), ('--line', n['dark'][4]), ('--chip', n['dark'][1])]
        cols = [h['dark'][9] for h in v['hues']] + [h['dark'][10] for h in v['hues']]
    rows += [(f'--c{i}', c) for i, c in enumerate(cols)]
    return sel + '{' + ';'.join(f'{k}:{val}' for k, val in rows) + '}'
for k, v in d.items():
    out.append(block(f'[data-pal="{k}"]', v, 'light'))
out.append('@media (prefers-color-scheme: dark){')
for k, v in d.items():
    out.append(block(f'[data-pal="{k}"]', v, 'dark'))
out.append('}')
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'palette.css'), 'w').write('\n'.join(out) + '\n')
print('\n'.join(f"{k}: {v['title']}" for k, v in d.items()))
